/**
 * Редизайн кабинета Ф5а (2026-06-13) — авто-название встреч.
 *
 * Хелпер-гейт: определяет, является ли текущий `Meeting.title` «пустым/мусорным»
 * плейсхолдером, который МОЖНО перезаписать авто-сгенерированным названием.
 *
 * Чистая функция без зависимостей — отдельным файлом, чтобы тестировать таблицей
 * без поднятия DI/Prisma/LLM.
 */

/**
 * Набор плейсхолдер-значений title встречи, которые считаем «не заданными
 * пользователем осмысленно». Сравнение — case-insensitive по trim'нутому
 * значению. Сюда же попадают служебные дефолты, которые проставляются при
 * быстром создании встречи без ввода названия.
 */
const PLACEHOLDER_TITLES = new Set<string>([
  '.',
  'текст',
  'встреча',
  'команда',
  'новая встреча',
  'без названия',
]);

/**
 * true → title можно перезаписать авто-названием. Критерии (любой):
 *   - пусто / только пробелы;
 *   - длина < 3 символов (после trim);
 *   - точное совпадение (case-insensitive) с одним из PLACEHOLDER_TITLES.
 *
 * Осмысленный пользовательский title (например «Синк по релизу») → false:
 * НЕ перезаписываем.
 */
export function isPlaceholderMeetingTitle(title: string | null | undefined): boolean {
  if (title == null) return true;
  const trimmed = title.trim();
  if (trimmed.length === 0) return true;
  if (trimmed.length < 3) return true;
  return PLACEHOLDER_TITLES.has(trimmed.toLowerCase());
}
