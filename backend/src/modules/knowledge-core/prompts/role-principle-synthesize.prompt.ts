export const ROLE_PRINCIPLE_SYNTHESIZE_USER_TEMPLATE = (args: {
  roleName: string;
  groups: ReadonlyArray<{
    label: string;
    quotes: ReadonlyArray<{ blockId: string; quote: string; observedAt: string }>;
  }>;
}): string => {
  const groupsText = args.groups.length
    ? args.groups
        .map((g, gi) => {
          const lines = g.quotes
            .map(
              (q, i) =>
                `  ${i + 1}. [${q.observedAt}] «${q.quote.slice(0, 600)}» (block=${q.blockId})`,
            )
            .join('\n');
          return `Группа ${gi + 1} — «${g.label}»:\n${lines}`;
        })
        .join('\n\n')
    : '(групп нет)';
  return [
    'Извлеки обобщённые принципы процесса должности из групп reasoning-цитат её носителей.',
    'Верни JSON-объект по схеме `role_principle_synthesize_v1`.',
    '',
    `Должность: ${args.roleName}.`,
    `Найдено ${args.groups.length} групп(ы) цитат (сгруппированы по похожим ситуациям):`,
    '',
    groupsText,
  ].join('\n');
};

