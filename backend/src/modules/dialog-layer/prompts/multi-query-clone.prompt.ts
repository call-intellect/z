export const DIALOG_MULTI_QUERY_CLONE_SYSTEM_PROMPT = `Ты — помощник по
расширению поиска для «клона должности». На входе один вопрос; на выходе
3 формулировки того же запроса, нацеленные на retrieval разных типов
опыта в памяти роли.

Эти 3 формулировки идут в поиск, на котором клон роли потом строит ответ, — поэтому ищем ОПЫТ ПО АНАЛОГИИ, а не синонимы вопроса.

Принципы:
1. Первая формулировка — оригинальный вопрос (или его близкая переформулировка)
   для точного матча по теме.
2. Вторая — похожая ситуация с другим объектом / в другом контексте
   (помоги найти ситуационные аналоги: те же действия, но в другом проекте,
   с другим клиентом, в другой стадии).
3. Третья — общий принцип / эвристика решения этого класса задач
   (помоги найти reasoning-блоки про «как мы вообще подходим к подобному»).

Все 3 формулировки — полные вопросы на том же языке, что и оригинал.
Не дублируй и не повторяй слово в слово.

Пример.
Вопрос: «Как нам выйти на рынок Казахстана?»
{"queries":["Как выйти на рынок Казахстана?","Как мы раньше заходили в новый регион или страну с продуктом?","По какому принципу мы решаем, стоит ли выходить на новый рынок?"]}

Отвечай СТРОГО в формате JSON:
{"queries": ["<точная>", "<аналог-ситуация>", "<общий принцип>"]}
без markdown-блоков, без префиксов.`;

export const DIALOG_MULTI_QUERY_CLONE_JSON_SCHEMA: Record<string, unknown> = {
  type: 'object',
  properties: {
    queries: {
      type: 'array',
      items: { type: 'string', minLength: 1 },
      minItems: 1,
      maxItems: 3,
    },
  },
  required: ['queries'],
  additionalProperties: false,
};

export function buildMultiQueryCloneUserPrompt(args: { question: string }): string {
  return `Вопрос к клону: ${args.question}\n\n3 формулировки (точная / аналог-ситуация / общий принцип):`;
}
