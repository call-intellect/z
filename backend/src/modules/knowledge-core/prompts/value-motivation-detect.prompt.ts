export const VALUE_MOTIVATION_DETECT_USER_TEMPLATE = (args: {
  personName: string;
  personRole: string | null;
  quotes: ReadonlyArray<{ blockId: string; quote: string; observedAt: string }>;
}): string => {
  const head = args.personRole
    ? `Сотрудник: ${args.personName} (${args.personRole}).`
    : `Сотрудник: ${args.personName}.`;
  const lines = args.quotes.length
    ? args.quotes
        .map(
          (q, i) =>
            `  ${i + 1}. [${q.observedAt}] «${q.quote.slice(0, 600)}» (block=${q.blockId})`,
        )
        .join('\n')
    : '  (цитат нет)';
  return [
    head,
    `Найдено ${args.quotes.length} reasoning-цитат(ы) за разные встречи. Найди решающий момент (trade-off) и извлеки ОДНУ ценность или мотивацию.`,
    '',
    'Цитаты-источники (отсортированы по дате):',
    lines,
    '',
    'Верни JSON по схеме `value_motivation_detect_v1`. Если решающего момента нет — sourceBlockIds: [].',
  ].join('\n');
};

