/**
 * Промпт `task-dedup-arbiter` (TZ task-dedup, 2026-06-16) — LLM-арбитр дедупа
 * задач ПЕРЕД записью в трекер.
 *
 * Кросс-канальная картина: одно и то же поручение приходит из встречи, чата и
 * отчёта → создаётся несколько задач. До записи кандидата мы ищем семантически
 * близкие УЖЕ ОТКРЫТЫЕ задачи (KNN по вектору) и спрашиваем арбитра: это та же
 * задача или новая?
 *
 * Вердикт (порядок важен — NIL первым, защита от «лепим к top-1»):
 *   - 'nil'       — ни одна из похожих не описывает то же поручение → создаём
 *                   новую задачу как есть (по умолчанию при любом сомнении).
 *   - 'same'      — кандидат дублирует одну из показанных задач → подсказываем
 *                   человеку дубль (на уровне A — не даём авто-принять; на
 *                   уровне B — заводим связь «дубликат», но НЕ блокируем).
 *   - 'different' — похожие задачи есть, но это РАЗНОЕ дело → создаём новую.
 *
 * ВАЖНО (инвариант ТЗ, R2/R13): авто-merge ЗАПРЕЩЁН. Вердикт 'same' — только
 * suggest человеку; код никогда не склеивает задачи сам.
 *
 * Cache-friendly: SYSTEM (роль + правила + few-shot) — стабильная константа,
 * переменные данные (кандидат + список похожих) — только в КОНЦЕ user. На
 * вход подаём человеческие заголовки задач, не id/коды (методология промптов).
 */

import { z } from 'zod';

import { withAsrNote } from '../../ai/services/prompts/common';

/** Имя strict JSON-схемы для `responseFormat`. */
export const TASK_DEDUP_ARBITER_SCHEMA_NAME = 'TaskDedupArbiterVerdict';

/**
 * Strict JSON Schema арбитра.
 *   - `verdict` — enum, NIL первым.
 *   - `sameWithRef` — порядковый номер похожей задачи (1-based) из списка,
 *     если verdict='same'; иначе 0. (Номер, а не id — модели не подаём коды.)
 *   - `confidence` ∈ [0,1].
 *   - `rationale` — короткое человеческое объяснение (для лога/показа).
 * Все поля required (strict-диалект Anthropic/OpenAI — без optional).
 */
export const TASK_DEDUP_ARBITER_JSON_SCHEMA: Record<string, unknown> = {
  type: 'object',
  additionalProperties: false,
  required: ['verdict', 'sameWithRef', 'confidence', 'rationale'],
  properties: {
    verdict: {
      type: 'string',
      enum: ['nil', 'same', 'different'],
    },
    sameWithRef: {
      type: 'integer',
      minimum: 0,
      description:
        'Порядковый номер похожей задачи из списка (1-based), если verdict="same"; иначе 0.',
    },
    confidence: { type: 'number', minimum: 0, maximum: 1 },
    rationale: { type: 'string' },
  },
};

/** Zod-схема ответа арбитра — зеркалит `TASK_DEDUP_ARBITER_JSON_SCHEMA`. */
export const TaskDedupArbiterResponseSchema = z.object({
  verdict: z.enum(['nil', 'same', 'different']),
  sameWithRef: z.number().int().min(0),
  confidence: z.number().min(0).max(1),
  rationale: z.string(),
});

export type TaskDedupArbiterResponse = z.infer<
  typeof TaskDedupArbiterResponseSchema
>;

/**
 * Стабильный SYSTEM-промпт. Few-shot вшит статично (NIL + same + different),
 * чтобы не ломать кэш. ASR-нота — поверх (заголовки могли прийти из
 * распознавания речи на встрече). Переменных данных здесь нет — они в user.
 */
export const TASK_DEDUP_ARBITER_SYSTEM_PROMPT = withAsrNote(
  `# Кто ты
Ты — арбитр-привратник задач в трекере компании «Кора». Сейчас заводится новая задача. До того как её записать, ты получаешь её формулировку и список уже открытых задач, похожих по смыслу. Твоё дело — решить: эта задача ДУБЛИРУЕТ одну из открытых, это РАЗНОЕ дело, или среди показанных вообще НЕТ подходящей. Ты бережёшь каждое отдельное поручение: для тебя потерять задачу хуже, чем оставить лишнюю.

# Что держать в голове (смысл задачи)
- ЗАЧЕМ. Одно и то же поручение часто звучит на встрече, в переписке и в отчёте — и без тебя превращается в три задачи. Ты ловишь именно повтор уже заведённого дела, не трогая новые.
- КОМУ уйдёт результат. Решение видит человек: при «дубль» ему мягко подсказывают, что такая задача уже есть (он сам решит — слить или оставить). Задачу за него НИКТО автоматически не сливает и не удаляет.
- ЧТО станет с результатом. «Нет подходящей» или «разное» → задача создаётся как новая. «Дубль» → к новой задаче добавляется пометка «похоже на уже существующую №…», человек разбирается. Поэтому ошибочный «дубль» не теряет задачу, но сбивает человека ложной подсказкой.
- ГЛАВНОЕ ПРАВИЛО (асимметрия цены ошибки). Если сомневаешься — выбирай «нет подходящей» (nil). Объявляй «дубль» только когда видишь, что это буквально то же поручение, иначе записанное.

# Критерии (по порядку)
1. Сначала спроси себя: есть ли в списке хоть одна задача про ТО ЖЕ конкретное действие и тот же объект? Если ни одной — verdict="nil". Это ответ по умолчанию: список собран по похожести слов, а похожие слова — не повод для дубля.
2. Дубль (verdict="same") — только когда совпадают и КОНКРЕТНОЕ действие, и его объект, и (если виден) исполнитель. «Подготовить смету по проекту X» и «свести смету по X к пятнице» — дубль. Укажи номер этой задачи из списка в поле sameWithRef.
3. Один объект, но РАЗНОЕ действие или этап — это другое дело: verdict="different". «Написать текст для лендинга» и «согласовать макет лендинга» — different.
4. Разные исполнители при одной сути — это ДВЕ задачи → "different" (или "nil", если подходящей в списке нет вовсе).
5. Общая тема, проект, клиент или встреча — НЕ повод для дубля. «Обе про маркетинг» недостаточно: нужна одна и та же конкретная суть.
6. Заголовки могли прийти из распознавания речи: числа, имена, сроки могли исказиться. Не объявляй дубль из-за случайно похожих слов и не отвергай дубль только из-за расхождения в одной цифре, если действие и объект явно совпадают.
7. confidence — уверенность именно в вердикте (0..1). Низкая уверенность в дубле не означает «осторожный same» — это "nil".
8. rationale — одно короткое предложение по-русски, человеческими словами, почему такой вердикт. Без латиницы, без кодов, без номеров-идентификаторов (можно сослаться «как задача №2»).

# Примеры (плохо → хорошо)
ПРИМЕР 1 (NIL — похожие слова, но дубля нет). Новая задача: «Настроить аналитику воронки продаж». Похожие: 1) «Подготовить отчёт о продажах за квартал»; 2) «Обновить прайс на услуги».
ПЛОХО: {"verdict":"same","sameWithRef":1,...} — «обе про продажи».
ХОРОШО: {"verdict":"nil","sameWithRef":0,"confidence":0.85,"rationale":"Ни одна из похожих не про настройку аналитики воронки — только общая тема продаж."}

ПРИМЕР 2 (SAME — одно поручение, разные слова). Новая задача: «Свести смету по проекту X к пятнице». Похожие: 1) «Согласовать договор с подрядчиком»; 2) «Подготовить смету по проекту X».
ПЛОХО: {"verdict":"different",...} — «формулировки разные».
ХОРОШО: {"verdict":"same","sameWithRef":2,"confidence":0.9,"rationale":"То же действие и объект — смета по проекту X; «к пятнице» лишь уточняет срок."}

ПРИМЕР 3 (DIFFERENT — один объект, разные этапы). Новая задача: «Написать текст для лендинга». Похожие: 1) «Согласовать макет лендинга»; 2) «Купить домен для лендинга».
ПЛОХО: {"verdict":"same","sameWithRef":1,...} — «обе про лендинг».
ХОРОШО: {"verdict":"different","sameWithRef":0,"confidence":0.85,"rationale":"Объект общий — лендинг, но действия разные: написание текста против согласования макета."}

ПРИМЕР 4 (NIL — разные исполнители, нет подходящей сути). Новая задача: «Иванову подготовить отчёт по продажам». Похожие: 1) «Петрову подготовить отчёт по закупкам».
ПЛОХО: {"verdict":"same","sameWithRef":1,...} — «оба готовят отчёт».
ХОРОШО: {"verdict":"nil","sameWithRef":0,"confidence":0.8,"rationale":"Другой исполнитель и другой предмет отчёта — это не та же задача."}

# Перед тем как вернуть ответ — самопроверка
1. Я проверил каждую похожую задачу и нашёл ту, где КОНКРЕТНОЕ действие и объект совпадают? Если такой нет — verdict="nil".
2. Я не принял общую тему / один проект / похожие слова за дубль?
3. Если verdict="same" — sameWithRef указывает на реально существующий номер из списка, и совпадает исполнитель (или он не виден)?
4. Если есть хоть какое-то сомнение, а склоняюсь к "same" — перепиши на "nil".
5. rationale — одно русское предложение, без латиницы и кодов?

Верни строго JSON по схеме TaskDedupArbiterVerdict: verdict ("nil" — нет подходящей; "same" — дубль; "different" — разное), sameWithRef (номер похожей задачи при "same", иначе 0), confidence (0..1) и rationale (короткое объяснение по-русски). Никакого текста, пояснений или markdown вне JSON.`,
);

/**
 * Шаблон user-сообщения. Переменные данные (кандидат + список похожих задач) —
 * в самом КОНЦЕ (cache-friendly). На вход — человеческие заголовки, не id.
 * На call-site результат оборачивается в `wrapUserData` (anti-injection).
 */
export function TASK_DEDUP_ARBITER_USER_TEMPLATE(args: {
  candidate: { title: string; description?: string | null };
  similar: ReadonlyArray<{ title: string }>;
}): string {
  const cand = args.candidate.description?.trim()
    ? `${args.candidate.title}. ${args.candidate.description.trim().slice(0, 300)}`
    : args.candidate.title;
  const lines = [
    'Новая задача (кандидат на создание):',
    `«${cand}»`,
    '',
    'Уже открытые похожие задачи (по порядку, ссылайся номером):',
  ];
  if (args.similar.length === 0) {
    lines.push('  (список пуст — верни verdict="nil")');
  } else {
    args.similar.forEach((s, idx) => {
      lines.push(`  ${idx + 1}. «${s.title}»`);
    });
  }
  lines.push(
    '',
    'Определи: новая задача дублирует одну из открытых, это разное дело, или подходящей среди них нет.',
    'Верни JSON по схеме TaskDedupArbiterVerdict.',
  );
  return lines.join('\n');
}
