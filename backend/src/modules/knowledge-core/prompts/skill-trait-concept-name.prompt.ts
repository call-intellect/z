export const SKILL_TRAIT_CONCEPT_NAME_USER_TEMPLATE = (args: {
  variants: ReadonlyArray<string>;
}): string => {
  const list = args.variants.length
    ? args.variants
        .map((v, i) => `  ${i + 1}. «${v}»`)
        .join('\n')
    : '  (вариантов нет — это баг вызова)';
  return [
    'Формулировки одной черты, признанные дубликатами:',
    list,
    '',
    'Верни JSON-объект по схеме `skill_trait_concept_name_v1`.',
  ].join('\n');
};

