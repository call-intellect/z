export function buildUnderstandUserPrompt(args: {
  summary: string | null;
  history: Array<{ role: 'user' | 'assistant'; content: string }>;
  question: string;
  todayIso: string;
  orgTimezone: string;
  knownNames?: ReadonlyArray<string>;
}): string {
  const summaryBlock =
    args.summary && args.summary.trim().length > 0 ? args.summary.trim() : '(нет)';

  const historyBlock =
    args.history.length > 0
      ? args.history
          .map((m) => `— ${m.role === 'user' ? 'Пользователь' : 'Ассистент'}: ${m.content}`)
          .join('\n')
      : '(диалог только начался)';

  const knownNamesBlock =
    args.knownNames && args.knownNames.length > 0
      ? `\n\nИзвестные названия компании, возможно относящиеся к вопросу:\n${args.knownNames.map((n) => `— ${n}`).join('\n')}`
      : '';

  return `Сегодня: ${args.todayIso}. Таймзона компании: ${args.orgTimezone}.

Краткое содержание диалога:
${summaryBlock}

Последние сообщения диалога:
${historyBlock}${knownNamesBlock}

Реплика пользователя:
${args.question}

Понимание (queries + plan):`;
}
