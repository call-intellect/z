const PROMPT_SAMPLE_SIZE = 8;
const BLOCK_INGEST_SAMPLE_SIZE = 3;

function promptSample(): readonly TaskDecisionPair[] {
  return TASK_VS_DECISION_PAIRS.slice(0, PROMPT_SAMPLE_SIZE);
}

export function renderExamplesForDecisionExtractor(): string {
  return [
    '# Примеры: что решение, а что задача (НЕ путай)',
    ...promptSample().flatMap((p) => [
      `- РЕШЕНИЕ (isDecision=true): «${p.decision}» — зафиксированный выбор.`,
      `- ЗАДАЧА/ПОРУЧЕНИЕ (isDecision=false): «${p.task}» — действие к исполнению, не выбор; это не решение.`,
    ]),
  ].join('\n');
}

export function renderExamplesForTaskExtractor(): string {
  return [
    '# Примеры: что задача, а что решение (НЕ путай)',
    ...promptSample().flatMap((p) => [
      `- ЗАДАЧА (isTask=true): «${p.task}» — конкретное действие к исполнению.`,
      `- РЕШЕНИЕ (isTask=false): «${p.decision}» — зафиксированный выбор, не задача; его берёт другой агент.`,
    ]),
  ].join('\n');
}

export function renderRuleForBlockIngest(): string {
  return [
    TASK_VS_DECISION_RULE,
    'Классификация сигнала:',
    ...TASK_VS_DECISION_PAIRS.slice(0, BLOCK_INGEST_SAMPLE_SIZE).flatMap((p) => [
      `- «${p.decision}» → signalType=decision (зафиксированный выбор).`,
      `- «${p.task}» → signalType=action_item (поручение/действие, НЕ decision).`,
    ]),
  ].join('\n');
}
