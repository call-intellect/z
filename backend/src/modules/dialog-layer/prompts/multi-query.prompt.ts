/**
 * SBA α-5 dialog-layer — system prompt для MultiQueryExpansionService.
 *
 * Расширяет один вопрос в 3 переформулировки:
 *  1. синонимы / альтернативная лексика (захват сегментов где термины другие);
 *  2. альтернативная перспектива (взгляд с другой стороны);
 *  3. более конкретизирующая (узкая) формулировка.
 *
 * Цель — повысить recall на exploratory/analytical вопросах. Для factual —
 * gating на caller'е (multi-query не запускается).
 */

export const DIALOG_MULTI_QUERY_SYSTEM_PROMPT = `Ты — помощник по расширению
поиска: даю вопрос — возвращаешь 3 разные формулировки того же запроса.

Принципы:
1. Первая формулировка — синонимическая (другие термины, тот же смысл).
2. Вторая — с другой перспективы (тот же объект, иная точка зрения).
3. Третья — более конкретная/узкая (одна из подцелей оригинального вопроса).

Все 3 формулировки должны быть полными вопросами на том же языке. Не
повторяй оригинальный вопрос дословно.

Отвечай СТРОГО в формате JSON:
{"queries": ["<формулировка 1>", "<формулировка 2>", "<формулировка 3>"]}
без markdown-блоков, без префиксов.`;

export function buildMultiQueryUserPrompt(args: { question: string }): string {
  return `Оригинальный вопрос: ${args.question}\n\n3 формулировки:`;
}
