/**
 * Ф0 (ТЗ 2026-06-16 task-dedup-and-tracker-reconcile) — объективный ГЕЙТ
 * качества перед материализацией задачи из AI-источника.
 *
 * Фундамент дедупа и закрытия: если в трекер попадает «мусор» (вопрос /
 * намерение без ответственного и без срока), дедуп и петля закрытия лишь
 * масштабируют его. Поэтому ДО `intakeIssue.create` из AI-источника спрашиваем
 * детерминированную функцию-правила (НЕ LLM, без сети): «это похоже на
 * поручение/решение, которое стоит превращать в задачу?».
 *
 * Граница (§6 ТЗ): сам LLM-классификатор интента «вопрос/намерение ≠ задача»
 * владеет СМЕЖНОЕ ТЗ (intent-questions). Здесь гейт работает по тем сигналам,
 * что УЖЕ доступны на месте создания:
 *   - тип/форма заголовка (детерминированно отличаем вопрос/намерение от
 *     поручения по поверхностным маркерам русского языка);
 *   - наличие явного владельца (ownerUserId / ownerHint);
 *   - наличие срока (dueDate);
 *   - источник (`decision`/`meeting`-решение считаем доверенным).
 *
 * Правило (ТЗ §10 Ф0): пропускаем создание ТОЛЬКО если
 *   (форма НЕ вопрос/намерение) И (есть owner ИЛИ срок ИЛИ источник = решение).
 *
 * Консервативность: при сомнении НЕ материализуем (лучше пропустить мусор, чем
 * заспамить трекер), но НИКОГДА не бросаем — поток создания не должен падать
 * из-за гейта. Вызывающий код просто не создаёт IntakeIssue и логирует reason.
 */

/**
 * Источники-РЕШЕНИЯ: задача доверенная даже без owner/срока И без форм-гейта —
 * это уже зафиксированный итог (решение), а не реплика. Материализуем всегда
 * (при непустом тексте).
 */
const DECISION_SOURCES = new Set<string>(['decision']);

/**
 * Источники «осознанного создания пользователем»: человек сам инициировал
 * задачу через канал (личное сообщение боту, форвард → задача, «следующий шаг»
 * отчёта встречи). Здесь отправитель = неявный владелец, поэтому требование
 * «owner ИЛИ срок» снимаем, НО форм-гейт (отсеять вопрос/намерение) применяем —
 * именно он отлавливает реальный мусор в этих каналах.
 *
 * [ASSUMPTION: для telegram/telegram_forward/meeting_next_step owner/срок часто
 *  не извлекаются (адресат подразумевается), а строгое требование «owner ИЛИ
 *  срок» зарубило бы законные self-task — потому форм-гейт достаточен; meeting
 *  (авто-извлечение из транскрипта) остаётся под полным правилом owner/срок.]
 */
const DELIBERATE_SOURCES = new Set<string>([
  'telegram',
  'telegram_forward',
  'meeting_next_step',
]);

/**
 * Поверхностные маркеры «вопрос» — строка-вопрос почти никогда не поручение.
 * Детерминированно, без LLM: знак вопроса в конце ИЛИ вопросительное слово в
 * начале. После слова требуем пробел или конец строки `(?=\s|$)` — `\b` в JS
 * не работает с кириллицей (ASCII-only), а так «что-то/кто-нибудь» (через дефис,
 * неопределённые местоимения — НЕ вопрос) не ловятся. Намеренно консервативно
 * (немного ложных срабатываний приемлемо — см. инвариант «при сомнении не
 * материализуем»).
 */
const QUESTION_PREFIX_RE =
  /^(как|какие|какой|какая|какое|что|зачем|почему|когда|где|куда|кто|можно ли|нужно ли|стоит ли)(?=\s|$)/iu;

/**
 * Маркеры «намерение/обсуждение» без обязательства — не поручение.
 * «надо бы», «хорошо бы», «может быть», «давайте обсудим», «думаю о», «идея».
 */
const INTENT_PHRASE_RE =
  /(надо бы|хорошо бы|неплохо бы|может быть(?![а-яё])|возможно стоит|давайте обсудим|стоит обсудить|думаю о |думаем о |идея[:\s]|обсудить(?![а-яё])|подумать над|рассмотреть вариант)/iu;

export interface TaskQualityGateInput {
  /** Извлечённый заголовок/суть будущей задачи (обязателен). */
  title: string | null | undefined;
  /** Явный владелец (резолвнутый userId). Любая непустая строка = есть owner. */
  ownerUserId?: string | null;
  /** Сырой текст-подсказка исполнителя (ФИО), если userId не резолвнулся. */
  ownerHint?: string | null;
  /** Срок (любое непустое значение = срок задан). */
  dueDate?: Date | string | null;
  /** Источник задачи: 'meeting' | 'telegram' | 'telegram_forward' | 'decision' | … */
  source: string;
}

export interface TaskQualityGateResult {
  ok: boolean;
  reason?: string;
}

/** Есть ли непустой владелец (резолвнутый userId ИЛИ текстовая подсказка). */
function hasOwner(input: TaskQualityGateInput): boolean {
  if (typeof input.ownerUserId === 'string' && input.ownerUserId.trim().length > 0) {
    return true;
  }
  const hint = (input.ownerHint ?? '').trim();
  return hint.length >= 2;
}

/** Есть ли срок (Date или непустая строка). */
function hasDue(input: TaskQualityGateInput): boolean {
  const d = input.dueDate;
  if (d == null) return false;
  if (d instanceof Date) return !Number.isNaN(d.getTime());
  return typeof d === 'string' && d.trim().length > 0;
}

/**
 * Детерминированный гейт качества: материализовать ли задачу из AI-источника.
 * Чистая функция, без сети, без LLM, не бросает.
 */
export function shouldMaterializeTask(
  input: TaskQualityGateInput,
): TaskQualityGateResult {
  const title = (input.title ?? '').trim();
  if (title.length === 0) {
    return { ok: false, reason: 'empty_title' };
  }

  // Источник-решение: уже зафиксированное обязательство — материализуем без
  // форм-гейта и без требования owner/срок (это итог, а не реплика).
  if (DECISION_SOURCES.has(input.source)) {
    return { ok: true };
  }

  // Форма «вопрос / намерение» = НЕ поручение. Применяется КО ВСЕМ остальным
  // источникам (в т.ч. «осознанным» telegram/next-step) — это и есть основной
  // фильтр мусора в разговорных каналах.
  if (QUESTION_PREFIX_RE.test(title) || title.endsWith('?')) {
    return { ok: false, reason: 'looks_like_question' };
  }
  if (INTENT_PHRASE_RE.test(title)) {
    return { ok: false, reason: 'looks_like_intent' };
  }

  // Осознанное создание пользователем (telegram/forward/next-step): отправитель
  // = неявный владелец → owner/срок не требуем (форм-гейт уже пройден).
  if (DELIBERATE_SOURCES.has(input.source)) {
    return { ok: true };
  }

  // Прочие AI-источники (meeting — авто-извлечение из транскрипта): полное
  // правило (форма НЕ вопрос/намерение) И (есть owner ИЛИ срок).
  if (hasOwner(input) || hasDue(input)) {
    return { ok: true };
  }

  // Поручение по форме, но без ответственного и без срока → пока «мусор»:
  // консервативно НЕ материализуем (человек/петля доформулирует позже).
  return { ok: false, reason: 'no_owner_no_due' };
}
