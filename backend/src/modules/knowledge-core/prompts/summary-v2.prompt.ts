interface BuildArgs {
  meetingType: MeetingType;
  meetingTitle?: string | undefined;
  blocks: MeetingBlock[];
}

/**
 * Собирает {system, user} промпты для summary-v2 LLM-вызова. Output —
 * markdown-текст; LlmRouter возвращает result.text как есть.
 *
 * @deprecated С 2026-05-25 заменён на объединённый промпт
 * `meeting-report-fast` (`backend/src/modules/ai/services/prompts/meeting-report-fast.prompt.ts`).
 * См. ТЗ `plans/tz/2026-05-25-meeting-report-split-from-block-ingest.md`,
 * Фаза 6. Промпт пока остаётся для A/B-сравнения; удалить после 2 недель
 * параллельной работы и положительной обратной связи от продакт-менеджера.
 */
export function buildSummaryV2Prompt(args: BuildArgs): {
  system: string;
  user: string;
} {
  const system = SYSTEM_BY_TYPE[args.meetingType] ?? SYSTEM_BY_TYPE.team;

  const blocksJson = args.blocks.map((b) => {
    const firstEv = b.evidence[0];
    return {
      id: b.id,
      name: b.name,
      criticalQuestion: b.criticalQuestion,
      trustedAnswer: b.trustedAnswer,
      signalType: b.signalType,
      tags: b.tags,
      evidenceQuote: firstEv?.quote ?? null,
    };
  });

  const header = args.meetingTitle
    ? `Заголовок встречи: ${args.meetingTitle}\nТип: ${args.meetingType}\n\n`
    : `Тип: ${args.meetingType}\n\n`;

  const user = `${header}Канонические блоки знания встречи (в хронологии):\n${JSON.stringify(
    blocksJson,
    null,
    2,
  )}\n\nНапиши итоговую сводку в markdown по правилам system-промпта. Не возвращай JSON, не оборачивай в \`\`\`. Только markdown-текст.`;

  return { system, user };
}
