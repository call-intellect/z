import { withAsrNote, withInjectionGuard, wrapUserData } from './common';

const EXTRACT_COLUMN_TYPE_CATALOG: ReadonlyArray<[type: string, ru: string]> = [
  ['text', 'короткая строка'],
  ['longtext', 'длинный текст / заметка'],
  ['number', 'число (верни как число, без пробелов-разделителей)'],
  ['currency', 'денежная сумма (верни число в рублях; «два миллиона» → 2000000)'],
  ['percent', 'процент (верни число 0..100)'],
  [
    'date',
    'дата в формате ГГГГ-ММ-ДД. Если в транскрипте только относительная формулировка («к пятнице», «в следующем месяце») и конкретная ISO-дата не известна — НЕ возвращай эту колонку (не угадывай дату).',
  ],
  ['status', 'одно из допустимых значений статуса колонки (из схемы)'],
  ['selectSingle', 'одно значение из набора (из схемы)'],
  ['selectMulti', 'массив значений из набора (из схемы)'],
  ['checkbox', 'да/нет (true/false)'],
  ['url', 'ссылка (адрес сайта)'],
  ['email', 'электронная почта'],
  ['phone', 'телефон'],
];

export interface ExtractRowsPropertySchemaItem {
  id: string;
  name: string;
  type: string;
  hint?: string;
}

export interface BuildTableExtractRowsPromptArgs {
  propertySchema: ReadonlyArray<ExtractRowsPropertySchemaItem>;
  transcriptChunk: string;
  entityLabel: string;
  meetingDateIso?: string | null;
}

function buildSystem(): string {
  const typeLines = EXTRACT_COLUMN_TYPE_CATALOG.map(([t, ru]) => `  - \`${t}\` — ${ru}`).join('\n');

  return withAsrNote(
    withInjectionGuard(
      [
        '## Роль',
        'Ты — агент памяти компании Кора. Из фрагмента транскрипта встречи ты извлекаешь факты, которые можно записать в колонки умной таблицы для указанной сущности. Только прямо названные факты — никаких выводов «по смыслу».',
        '',
        '## Главный принцип — только явное и только об этой сущности',
        'Возвращай факт по колонке ИСКЛЮЧИТЕЛЬНО если:',
        '1. факт прямо назван в транскрипте (цитата есть), И',
        '2. факт относится к сущности из `entityLabel` (не к другому участнику, компании или проекту).',
        'Если сомневаешься, что это именно эта сущность — не возвращай. Лучше пропустить, чем ошибиться сущностью.',
        '',
        '## Несколько упоминаний одного факта',
        'Если одна колонка упоминается несколько раз с разными значениями (например, сумма менялась в ходе встречи) — возвращай ПОСЛЕДНЕЕ по времени значение. В `quote` приведи именно эту финальную реплику.',
        '',
        '## Типы колонок (как форматировать value)',
        typeLines,
        '',
        '## Поля каждого факта',
        '- `propertyId` — ровно тот `id` колонки из схемы. Не выдумывай чужих id.',
        '- `value` — значение в формате типа колонки (см. выше).',
        '- `confidence` (0..1) — насколько явно факт назван:',
        '  · 0.9–1.0: прямая однозначная реплика («бюджет — 500 000 рублей»)',
        '  · 0.6–0.89: явно сказано, но есть контекстная неоднозначность',
        '  · ниже 0.6: сомнительно — лучше не возвращать вовсе, чем ставить низкий confidence',
        '- `quote` — дословная цитата из транскрипта, подтверждающая именно это значение.',
        '- `timeSec` — секунда начала реплики-источника; 0 если не известна.',
        '',
        '## Формат вывода',
        'Верни СТРОГО валидный JSON-объект без markdown-обёрток и комментариев:',
        '`{ "facts": [ { "propertyId": string, "value": string|number|boolean|array, "confidence": number, "quote": string, "timeSec": number } ] }`',
        'Нет подтверждённых фактов → `{ "facts": [] }`.',
        '',
        '## Чего НЕ делать',
        '- Не выводить значение «по смыслу», не обобщать, не достраивать.',
        '- Не смешивать факты разных сущностей (строго entityLabel).',
        '- Не угадывать ISO-дату из относительных оборотов при отсутствии якорной даты.',
        '- Не возвращать `propertyId`, которого нет в схеме.',
      ].join('\n'),
    ),
  );
}

const SYSTEM = buildSystem();

export function buildTableExtractRowsPrompt(args: BuildTableExtractRowsPromptArgs): {
  system: string;
  user: string;
} {
  const schemaLines = args.propertySchema
    .map((p) => `  - id=${p.id} | «${p.name}» | тип ${p.type}${p.hint ? ` | ${p.hint}` : ''}`)
    .join('\n');

  const dateAnchor = args.meetingDateIso
    ? `Дата встречи (якорь для относительных дат в date-колонках, разворачивай в ISO ГГГГ-ММ-ДД): ${args.meetingDateIso}`
    : 'Дата встречи неизвестна — относительные сроки в ISO не разворачивай, такие date-колонки пропускай.';

  const user = [
    `Сущность (строка таблицы): ${args.entityLabel}`,
    dateAnchor,
    '',
    'Колонки, которые можно заполнить:',
    schemaLines || '  (нет колонок)',
    '',
    'Фрагмент транскрипта встречи:',
    wrapUserData(args.transcriptChunk.trim()),
    '',
    'Верни JSON по правилам из системного сообщения. Возвращай только прямо подтверждённые факты.',
  ].join('\n');

  return { system: SYSTEM, user };
}
