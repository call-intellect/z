/**
 * Единая конфигурация поллинга бейджей навигации (A7, 2026-06-06).
 *
 * Раньше каждый badge-хук задавал refreshInterval вразнобой и без dedup,
 * из-за чего при каждой навигации между страницами летели повторные запросы
 * (`/intake?status=pending&limit=1`, `/me/inbox/count`, `/pending-actions/count`).
 * Эти константы централизуют интервал и добавляют dedup.
 */

/** Интервал фонового обновления второстепенных бейджей. */
export const BADGE_POLL_INTERVAL_MS = 60_000;

/**
 * Окно дедупликации одинаковых SWR-запросов бейджа: навигация между
 * страницами в пределах окна переиспользует кэш, не порождая новый запрос.
 * Должно быть ≤ BADGE_POLL_INTERVAL_MS, чтобы не «съедать» плановые опросы.
 */
export const BADGE_DEDUPE_MS = 30_000;
