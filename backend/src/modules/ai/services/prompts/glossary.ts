/**
 * Глоссарий бизнес-терминов Z (ТЗ 2026-05-24 §11 / F12).
 *
 * Точечный helper для подмешивания определений терминов в system-промпт.
 * Используется в промтах, где LLM должна различать близкие, но
 * семантически разные понятия (pain vs objection, decision vs preference,
 * regulation vs process и т.п.).
 *
 * Применять ТОЛЬКО когда промт явно работает с этими терминами — не
 * подмешивать «на всякий случай». Каждая лишняя строка в system —
 * +input-токены и шанс для модели «зацепиться» не за тот термин.
 *
 * Не применяется глобально. См. ТЗ §11 — это helper для будущих новых
 * промтов или точечных правок существующих.
 */

const GLOSSARY: Record<string, string> = {
  pain: 'Pain — реальная проблема клиента/пользователя, которую он озвучивает. ОТЛИЧАТЬ от objection (возражение на цену/продавца) и concern (опасение, не подкреплённое опытом).',
  churn_risk:
    'Churn risk — риск ухода клиента/пользователя. ОТЛИЧАТЬ от disengagement (временное снижение активности без намерения уйти).',
  commitment:
    'Commitment — публичное обязательство сделать X к сроку Y. ОТЛИЧАТЬ от intention (внутреннее намерение без публичной фиксации).',
  mentoring:
    'Mentoring — передача знаний/опыта с целью развития получателя. ОТЛИЧАТЬ от explaining (просто объяснение факта/процесса).',
  proactive_hint:
    'Proactive hint — подсказка/предупреждение, которое не было запрошено получателем, но полезно ему. ОТЛИЧАТЬ от unsolicited advice (нежелательный совет, который не помогает).',
  decision:
    'Decision — выбор из нескольких опций, зафиксированный с обоснованием. ОТЛИЧАТЬ от preference (личное предпочтение без обоснования).',
  regulation:
    'Regulation — формальное правило компании (что/нельзя). ОТЛИЧАТЬ от process (последовательность шагов как делать) и policy (общий принцип).',
};

/** Допустимые ключи глоссария. */
export type GlossaryTerm = keyof typeof GLOSSARY;

/**
 * Подмешивает к system-промпту блок «Глоссарий бизнес-терминов:» с
 * определениями только указанных терминов. Неизвестные ключи silently
 * пропускаются (защита от опечаток в коде). Пустой массив / отсутствие
 * валидных терминов → возвращает system без изменений.
 *
 * Применять ТОЛЬКО когда промт явно работает с этими терминами.
 *
 * @example
 *   const system = withGlossary(SYSTEM_PROMPT, ['pain', 'churn_risk']);
 */
export function withGlossary(
  systemBody: string,
  terms: readonly GlossaryTerm[],
): string {
  const definitions = terms
    .filter((t) => GLOSSARY[t])
    .map((t) => `- ${GLOSSARY[t]}`)
    .join('\n');
  if (!definitions) return systemBody;
  return `${systemBody}\n\nГлоссарий бизнес-терминов:\n${definitions}`;
}
