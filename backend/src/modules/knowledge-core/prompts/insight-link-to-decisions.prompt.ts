export const INSIGHT_LINK_TO_DECISIONS_USER_TEMPLATE = (args: {
  insightKind: string;
  insightStatement: string;
  candidates: readonly {
    id: string;
    statement: string;
    decidedAt: string | null;
    status: string;
  }[];
}): string => {
  const candidates = args.candidates.length
    ? args.candidates
        .map(
          (c, i) =>
            `  ${i + 1}. id=${c.id} | статус: ${decisionStatusLabelRu(c.status)} | принято: ${c.decidedAt ?? '—'} | «${c.statement.slice(0, 300)}»`,
        )
        .join('\n')
    : '  (кандидатов нет)';
  return [
    `Сигнал (${insightKindLabelRu(args.insightKind)}): «${args.insightStatement}».`,
    '',
    'Кандидаты-решения:',
    candidates,
    '',
    'Верни JSON-объект по схеме `insight_link_to_decisions_v1`.',
  ].join('\n');
};

