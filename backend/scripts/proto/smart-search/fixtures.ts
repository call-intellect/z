function norm(s: string): string {
  return s.toLowerCase().replace(/[ёе]/g, 'е').replace(/[^a-zа-я0-9]+/g, ' ');
}
function tokens(s: string): string[] {
  return norm(s).split(' ').filter((t) => t.length >= 3);
}

export interface Candidate extends Block {
  score: number;
}

export function naiveRetrieve(query: string, topK = 8): Candidate[] {
  const qt = new Set(tokens(query));
  const pool = process.env.PROTO_NOISE === '1' ? [...BLOCKS, ...NOISE_BLOCKS] : BLOCKS;
  const scored = pool.map((b) => {
    const bt = tokens(`${b.title} ${b.text} ${b.meetingTitle}`);
    let overlap = 0;
    for (const t of bt) if (qt.has(t)) overlap++;
    return { ...b, score: overlap };
  })
    .filter((b) => b.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, topK);
}
