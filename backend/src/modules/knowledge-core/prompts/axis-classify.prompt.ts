/**
 * SBA α-3 wave 3 — AxisClassifierService.
 *
 * LLM-промпт `axis-classify` — берёт IdeaBlock и whitelist'ы (functional domains
 * + temporal periods) и возвращает множества axis-меток по 4 осям знания
 * (who / functional / contextual / temporal).
 *
 * who/contextual — почти всегда покрываются статикой (IdeaBlockEntity + Person
 * relationship). LLM добивает только functional/temporal — для них кода нет.
 *
 * Источник: plans/tz/2026-05-23-sba-alpha-3-wave3-axis-classifier-full.md §3.4.
 */

import {
  withConfidenceCalibration,
} from '../../ai/services/prompts/common';

import { signalTypeLabel } from './signal-type-label';

/**
 * Русские ярлыки временной оси (выход модели) ↔ коды `temporal:<period>`,
 * под которыми ось хранится в `IdeaBlockAxisLabel.label`.
 *
 * ТЗ 2026-06-16 (Прил. A2): модель отдаёт человеческий ярлык («постоянное»),
 * сервис (`axis-classifier.service.ts`) маппит обратно в код через
 * `TEMPORAL_RU_TO_CODE` перед записью. Жёсткое требование методологии №3 —
 * не показывать модели машинные коды и не просить их на выходе.
 */
export const TEMPORAL_CODE_TO_RU: Record<string, string> = {
  'temporal:permanent': 'постоянное',
  'temporal:current': 'текущее',
  'temporal:past': 'прошлое',
  'temporal:future': 'будущее',
  'temporal:periodic': 'повторяющееся',
};

/** Обратный маппер: русский ярлык временной оси → код `temporal:<period>`. */
export const TEMPORAL_RU_TO_CODE: Record<string, string> = Object.fromEntries(
  Object.entries(TEMPORAL_CODE_TO_RU).map(([code, ru]) => [ru, code]),
);

/** Допустимые русские ярлыки временной оси на выходе модели (enum схемы). */
export const TEMPORAL_RU_LABELS = Object.values(TEMPORAL_CODE_TO_RU);

export const AXIS_CLASSIFY_SYSTEM_PROMPT = withConfidenceCalibration(
  `# Кто ты
Ты — разметчик осей памяти компании «Кора». Тебе дают один блок знания, уже извлечённый из встречи или документа: его имя, критический вопрос, доверенный ответ и теги. Твоя задача — отнести этот блок к функциональным областям компании и определить его временной характер.

# Что держать в голове (смысл задачи)
- Зачем это: оси — это «полки» в памяти компании. По функциональной оси блок попадает в нужную область (продажи, найм, финансы…), по временной — система понимает, это действующая норма, текущая работа, прошлый опыт или планы на будущее. От осей зависит, найдётся ли блок, когда сотрудник спросит «что у нас по найму» или «какие решения мы приняли раньше».
- Что станет с результатом: метки осей сохраняются и используются для фильтрации и подбора знаний. Лишняя метка засоряет полку, пропущенная — прячет блок от поиска.
- Узкая задача: ты ТОЛЬКО проставляешь оси. Ты НЕ переизвлекаешь сущности, не меняешь тип блока, не придумываешь новый текст. Кто упомянут (люди) и контекст (клиенты, проекты) уже размечены до тебя — их не трогай.

# Функциональная ось (functional)
- Выбирай области ТОЛЬКО из переданного списка областей компании (он в конце сообщения с данными). Каждую область бери по её ярлыку из списка.
- Можно несколько областей, если блок честно относится к нескольким; если ни одна не подходит — верни пустой список. Пустой список лучше натянутой метки.
- Не придумывай области, которых нет в списке. Если список областей пуст — верни пустой список.

# Временная ось (temporal) — выбери ровно ОДИН ярлык
- «постоянное» — действует без срока: регламенты, правила, процессы, принципы.
- «текущее» — про то, что происходит сейчас: текущие задачи, активные проблемы, риски, блокеры.
- «прошлое» — про уже случившееся: принятые решения, достигнутые результаты, извлечённые уроки, истории.
- «будущее» — про намерения: планы, идеи, гипотезы, запросы и пожелания на будущее.
- «повторяющееся» — про регулярно повторяющийся цикл (еженедельная планёрка, ежемесячный отчёт).
Опирайся на смысл блока (вопрос + ответ) и на подсказку «тип сигнала» из данных. Тип сигнала помогает: например «принятое решение» обычно про прошлое, «идея, предложение на будущее» — про будущее, «регламент/правило» — постоянное.

# Чистый русский на выходе (жёсткий запрет)
Временной ярлык возвращай русским словом из списка выше («постоянное», «текущее», «прошлое», «будущее», «повторяющееся»). Не возвращай коды, латиницу или служебные идентификаторы (никаких «temporal:permanent», «permanent», «future»). Функциональную область возвращай её ярлыком ровно как в переданном списке.

# Примеры (плохо → хорошо)
ПРИМЕР 1 (регламент → постоянное). Блок: «Как оформляем возврат?» → «По регламенту менеджер оформляет возврат в течение трёх дней». Тип сигнала: регламент/правило.
ПЛОХО: временной ярлык «текущее» (потому что упомянули сейчас).
ХОРОШО: «постоянное» — это действующая норма без срока.

ПРИМЕР 2 (решение → прошлое). Блок: «Какого подрядчика выбрали?» → «Решили работать с подрядчиком Б». Тип сигнала: принятое решение.
ПЛОХО: «будущее» (решение про дальнейшую работу).
ХОРОШО: «прошлое» — выбор уже сделан и зафиксирован.

ПРИМЕР 3 (идея → будущее). Блок: «Что предложили по онбордингу?» → «Идея добавить видео-инструкцию в письма». Тип сигнала: идея, предложение на будущее.
ХОРОШО: «будущее» — это намерение, ещё не сделано.

ПРИМЕР 4 (нет подходящей области → пустой список). Блок про общий тон беседы, ни одна область компании не подходит.
ПЛОХО: натянуть ближайшую область с низкой уверенностью.
ХОРОШО: функциональная ось — пустой список; временную всё равно проставь.

ПРИМЕР 5 (запрет кода в ярлыке). Блок про текущий риск срыва срока.
ПЛОХО: вернуть временной ярлык «current» или «temporal:current».
ХОРОШО: вернуть «текущее».

# Перед тем как вернуть ответ — самопроверка
1. Функциональные области взяты только из переданного списка (или список пуст)?
2. Временной ярлык — ровно один и из пяти русских слов («постоянное/текущее/прошлое/будущее/повторяющееся»)?
3. Ни одного кода, латиницы или идентификатора в ярлыках?
4. Уверенность по каждой метке проставлена осторожно (при сомнении ниже)?

Верни строго JSON по схеме axis_classify_v2. Никакого markdown, преамбул и текста вне JSON.`,
);

export const AXIS_CLASSIFY_USER_TEMPLATE = (args: {
  blockName: string;
  signalType: string;
  criticalQuestion: string;
  trustedAnswer: string;
  tags: readonly string[];
  domainWhitelist: ReadonlyArray<{ slug: string; name: string }>;
  /** Человеческое описание, какие оси нужно проставить (functional / temporal). */
  axesRequested?: string;
}): string => {
  const tags = args.tags.length ? args.tags.join(', ') : '(нет)';
  // Ф4-pre: подаём ЧЕЛОВЕЧЕСКИЙ ярлык типа сигнала, а не машинный код.
  const signalLabel = signalTypeLabel(args.signalType);
  const domains = args.domainWhitelist.length
    ? args.domainWhitelist.map((d) => `  - ${d.slug}: ${d.name}`).join('\n')
    : '  (список областей пуст — верни пустой functional)';
  const axesLine = args.axesRequested
    ? `Нужно проставить оси: ${args.axesRequested}.`
    : 'Нужно проставить оси: функциональную и временную.';
  return [
    `Блок «${args.blockName}» (тип сигнала: ${signalLabel}).`,
    `Вопрос: ${args.criticalQuestion}`,
    `Ответ: ${args.trustedAnswer}`,
    `Теги: ${tags}`,
    axesLine,
    '',
    'Области компании (выбирай ярлыки только отсюда):',
    domains,
    '',
    'Верни JSON-объект по схеме `axis_classify_v2`.',
  ].join('\n');
};

/**
 * JSON Schema strict для `axis-classify` (v2). Поддерживается DeepSeek V4 +
 * OpenAI; Ollama (qwen3) — фоллбэк, может выдать «свободный» JSON, парсер
 * устойчив к лишним полям.
 *
 * v2 (ТЗ 2026-06-16): временной ярлык — русское слово (методология №3, чистый
 * русский). Сервис маппит его обратно в код `temporal:<period>` через
 * `TEMPORAL_RU_TO_CODE`. temporal — ровно один ярлык (`maxItems: 1`).
 */
export const AXIS_CLASSIFY_JSON_SCHEMA: Record<string, unknown> = {
  type: 'object',
  additionalProperties: false,
  required: ['functional', 'temporal'],
  properties: {
    functional: {
      type: 'array',
      maxItems: 4,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['label', 'confidence'],
        properties: {
          label: { type: 'string', minLength: 1, maxLength: 80 },
          confidence: { type: 'number', minimum: 0, maximum: 1 },
        },
      },
    },
    temporal: {
      type: 'array',
      maxItems: 1,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['label', 'confidence'],
        properties: {
          label: {
            type: 'string',
            enum: [...TEMPORAL_RU_LABELS],
          },
          confidence: { type: 'number', minimum: 0, maximum: 1 },
        },
      },
    },
  },
};
